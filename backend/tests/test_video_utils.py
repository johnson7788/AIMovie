"""Tests for utils/video.py — concat_videos and download_video.

These tests verify the ffmpeg-based video concatenation using the actual
scene video files generated by previous pipeline runs.
"""

import os
import sys
import shutil
import tempfile
import unittest
from unittest.mock import patch, MagicMock

# Ensure backend is on path
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

from utils.video import concat_videos, download_video


class TestConcatVideos(unittest.TestCase):
    """Test concat_videos with real video files from the working directory."""

    @classmethod
    def setUpClass(cls):
        cls.temp_dir = tempfile.mkdtemp(prefix="test_concat_")
        cls.output_path = os.path.join(cls.temp_dir, "output.mp4")

        # Use existing scene videos as test data
        cls.scene_dir = os.path.join(
            os.path.dirname(__file__), "..",
            ".working_dir", "idea2video", "75975d5abb19795a"
        )

    @classmethod
    def tearDownClass(cls):
        shutil.rmtree(cls.temp_dir, ignore_errors=True)

    def setUp(self):
        if os.path.exists(self.output_path):
            os.remove(self.output_path)

    def _get_scene_videos(self, *scene_indices):
        paths = []
        for idx in scene_indices:
            p = os.path.join(self.scene_dir, f"scene_{idx}", "final_video.mp4")
            if os.path.exists(p):
                paths.append(p)
        return paths

    def test_concat_single_video_is_copy(self):
        """A single video should just be copied, not re-encoded."""
        videos = self._get_scene_videos(0)
        if not videos:
            self.skipTest("No scene videos available")
        result = concat_videos(videos, self.output_path)
        self.assertTrue(os.path.exists(result))
        self.assertGreater(os.path.getsize(result), 0)

    def test_concat_two_same_resolution(self):
        """Concatenating two 960x960 videos should work."""
        videos = self._get_scene_videos(0, 1)
        if len(videos) < 2:
            self.skipTest("Need at least 2 scene videos")

        result = concat_videos(videos, self.output_path)
        self.assertTrue(os.path.exists(result))
        self.assertGreater(os.path.getsize(result), 0)

        # Check output resolution
        import subprocess
        r = subprocess.run([
            "ffprobe", "-v", "error",
            "-show_entries", "stream=width,height",
            "-of", "default=noprint_wrappers=1:nokey=1",
            result,
        ], capture_output=True, text=True)
        lines = r.stdout.strip().split("\n")
        self.assertEqual(lines[0], "960")
        self.assertEqual(lines[1], "960")

    def test_concat_mixed_resolution(self):
        """Concatenating mixed resolutions (960x960 + 1282x720) should normalize to 960x960."""
        videos = self._get_scene_videos(2, 3)
        if len(videos) < 2:
            self.skipTest("Need scene_2 and scene_3 videos")

        result = concat_videos(videos, self.output_path)
        self.assertTrue(os.path.exists(result))
        self.assertGreater(os.path.getsize(result), 0)

        import subprocess
        r = subprocess.run([
            "ffprobe", "-v", "error",
            "-show_entries", "stream=width,height",
            "-of", "default=noprint_wrappers=1:nokey=1",
            result,
        ], capture_output=True, text=True)
        lines = r.stdout.strip().split("\n")
        self.assertEqual(lines[0], "960")
        self.assertEqual(lines[1], "960")

    def test_concat_all_four_scenes(self):
        """Concatenate all 4 scenes — simulates the full pipeline output."""
        videos = self._get_scene_videos(0, 1, 2, 3)
        if len(videos) < 4:
            self.skipTest("Need all 4 scene videos")

        result = concat_videos(videos, self.output_path)
        self.assertTrue(os.path.exists(result))
        size_mb = os.path.getsize(result) / (1024 * 1024)
        self.assertGreater(size_mb, 10, f"Expected >10MB output, got {size_mb:.1f}MB")

        # The output should be playable (no ffmpeg errors)
        import subprocess
        r = subprocess.run([
            "ffmpeg", "-v", "error", "-i", result, "-f", "null", "-",
        ], capture_output=True, text=True)
        self.assertEqual(r.returncode, 0, f"ffmpeg errors in output: {r.stderr}")

        # Check resolution is normalized
        r = subprocess.run([
            "ffprobe", "-v", "error",
            "-show_entries", "stream=width,height",
            "-of", "default=noprint_wrappers=1:nokey=1",
            result,
        ], capture_output=True, text=True)
        lines = r.stdout.strip().split("\n")
        self.assertEqual(lines[0], "960", "Width should be 960")
        self.assertEqual(lines[1], "960", "Height should be 960")

    def test_concat_rejects_empty_list(self):
        with self.assertRaises(ValueError):
            concat_videos([], self.output_path)

    def test_concat_output_is_playable(self):
        """The output should pass ffmpeg error check."""
        videos = self._get_scene_videos(0, 1)
        if len(videos) < 2:
            self.skipTest("Need at least 2 scene videos")

        result = concat_videos(videos, self.output_path)
        import subprocess
        r = subprocess.run([
            "ffmpeg", "-v", "error", "-i", result, "-f", "null", "-",
        ], capture_output=True, text=True)
        self.assertEqual(r.returncode, 0, f"ffmpeg errors: {r.stderr}")


